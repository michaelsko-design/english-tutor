"""
Measures where the drawn object sits inside each room icon (the icons have transparent padding)
and writes src/data/roomIconBounds.ts, so the room can put an item's feet and shadow on the
visible bottom edge instead of the picture's box.

Usage: python scripts/art/measure_icon_bounds.py
"""
import re
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ICONS = ROOT / 'public' / 'art' / 'icons'
ICON_ART = ROOT / 'src' / 'components' / 'art' / 'iconArt.ts'
ROOM_FILES = [ROOT / 'src' / 'data' / 'room.ts']
OUT = ROOT / 'src' / 'data' / 'roomIconBounds.ts'
ALPHA_MIN = 40
VARIATION_SELECTOR = '️'


def emoji_to_icon_id() -> dict:
    pairs = re.findall(r"'([^']+)':\s*'([a-z0-9-]+)'", ICON_ART.read_text(encoding='utf8'))
    return {emoji.replace(VARIATION_SELECTOR, ''): icon for emoji, icon in pairs}


def room_emoji() -> list:
    found = []
    for file in ROOM_FILES:
        found += re.findall(r"emoji: '([^']+)'", file.read_text(encoding='utf8'))
    return sorted({e.replace(VARIATION_SELECTOR, '') for e in found})


def measure(icon_id: str):
    image = Image.open(ICONS / f'{icon_id}.webp').convert('RGBA')
    alpha = np.asarray(image)[:, :, 3]
    ys, xs = np.where(alpha > ALPHA_MIN)
    if len(ys) == 0:
        return None
    h, w = alpha.shape
    return (round(xs.min() / w, 3), round((xs.max() + 1) / w, 3), round(ys.min() / h, 3), round((ys.max() + 1) / h, 3))


def main() -> None:
    mapping = emoji_to_icon_id()
    rows = []
    for emoji in room_emoji():
        icon_id = mapping.get(emoji)
        bounds = measure(icon_id) if icon_id else None
        if bounds:
            rows.append(f"  '{emoji}': {{ left: {bounds[0]}, right: {bounds[1]}, top: {bounds[2]}, bottom: {bounds[3]} }}, // {icon_id}")
        else:
            print('no icon for', emoji)
    OUT.write_text(
        "// Generated by scripts/art/measure_icon_bounds.py: where the drawn object sits in its icon (0-1 of the picture).\n"
        "export interface IconBounds {\n  left: number;\n  right: number;\n  top: number;\n  bottom: number;\n}\n\n"
        "export const ROOM_ICON_BOUNDS: Readonly<Record<string, IconBounds>> = {\n" + "\n".join(rows) + "\n};\n",
        encoding='utf8',
    )
    print(f'wrote {len(rows)} rows')


if __name__ == '__main__':
    main()
