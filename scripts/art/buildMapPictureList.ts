/**
 * Builds the map picture list from scripts/art/missionPictureTopics.mjs: every topic that needs
 * drawing gets a sheet and cell (16 per 4 × 4 sheet), and every unit badge and mission gets its
 * topic's picture id.
 *
 * Writes  scripts/art/mapPictureList.json       (input of `renderVocabPictures.mjs --set map` and the slicer)
 *         src/components/art/mapPictureIds.ts   (unit / mission → picture id, read by the app)
 * Existing entries keep their sheet and cell, so re-running only adds new topics on new sheets.
 *
 * Usage:  npx vite-node scripts/art/buildMapPictureList.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BASE_CURRICULUM_BY_GRADE } from '../../src/data/curriculum/base';
import { ALL_PACK_CURRICULA } from '../../src/data/curriculum/packs';
import { withPacks } from '../../src/data/curriculum/packs/merge';
import { CONTENT_PACK_IDS } from '../../src/data/curriculum/packs/registry';
// @ts-expect-error plain JS module shared with the review tools
import { SCREEN_TOPICS, TOPICS, UNIT_TOPICS } from './missionPictureTopics.mjs';

const ROOT = process.cwd();
const LIST_FILE = join(ROOT, 'scripts', 'art', 'mapPictureList.json');
const IDS_FILE = join(ROOT, 'src', 'components', 'art', 'mapPictureIds.ts');
const PER_SHEET = 16;

type Topic = string | { reuse: string };

interface Entry {
  key: string;
  id: string;
  /** Shown in the slicer's review page */
  word: string;
  he: string;
  subject: string;
  sheet: number;
  cell: number;
}

const topics = TOPICS as Record<string, Topic>;
const pictureIdOf = (key: string): string => {
  const topic = topics[key];
  if (topic === undefined) throw new Error(`No topic "${key}"`);
  if (typeof topic !== 'string') return topic.reuse;
  return key.startsWith('ui-') ? key : `map-${key}`;
};

/** Unit key `<gradeId>/<unitNumber>` and mission id → topic key, checked against the curriculum. */
function collectAssignments(): Map<string, string> {
  const assignments = new Map<string, string>();
  const all = withPacks(BASE_CURRICULUM_BY_GRADE, CONTENT_PACK_IDS, ALL_PACK_CURRICULA);
  for (const [gradeId, pack] of Object.entries(all)) {
    const grade = gradeId.split('-')[1];
    for (const unit of pack.units) {
      const row: string[] | undefined = (UNIT_TOPICS as Record<string, string[]>)[`${grade}-${unit.unitNumber}`];
      if (!row || row.length !== unit.missions.length + 1) throw new Error(`Topics for ${gradeId} unit ${unit.unitNumber} don't match its missions`);
      assignments.set(`${gradeId}/${unit.unitNumber}`, row[0]);
      unit.missions.forEach((mission, i) => assignments.set(mission.id, row[i + 1]));
    }
  }
  return assignments;
}

function buildList(drawnKeys: string[]): Entry[] {
  const previous: Entry[] = existsSync(LIST_FILE) ? JSON.parse(readFileSync(LIST_FILE, 'utf8')) : [];
  const wanted = new Set(drawnKeys);
  const kept = previous.filter((e) => wanted.has(e.key)).map((e) => ({ ...e, id: pictureIdOf(e.key), subject: topics[e.key] as string }));
  const taken = new Set(kept.map((e) => e.key));
  const entries = [...kept];
  let sheet = Math.max(0, ...entries.map((e) => e.sheet));
  let inSheet = PER_SHEET;
  for (const key of drawnKeys) {
    if (taken.has(key)) continue;
    if (inSheet === PER_SHEET) {
      sheet += 1;
      inSheet = 0;
    }
    entries.push({ key, id: pictureIdOf(key), word: key, he: '', subject: topics[key] as string, sheet, cell: inSheet });
    inSheet += 1;
  }
  return entries;
}

function writeIds(assignments: Map<string, string>): void {
  const lines = [...assignments].map(([where, key]) => `  ${JSON.stringify(where)}: ${JSON.stringify(pictureIdOf(key))},`);
  const screens = (SCREEN_TOPICS as string[]).map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(pictureIdOf(key))},`);
  writeFileSync(
    IDS_FILE,
    `/** Generated by scripts/art/buildMapPictureList.ts: unit ("<gradeId>/<unitNumber>") or mission id → drawn picture id. */
export const MAP_PICTURE_IDS: Readonly<Record<string, string>> = {
${lines.join('\n')}
};

/** Screen icons drawn in the same run (sign-in roles, settings tabs, …). */
export const SCREEN_PICTURE_IDS: Readonly<Record<string, string>> = {
${screens.join('\n')}
};

/** A unit badge's drawn picture. */
export function getUnitPictureId(gradeId: string, unitNumber: number): string | undefined {
  return MAP_PICTURE_IDS[\`\${gradeId}/\${unitNumber}\`];
}

/** A mission's drawn picture. */
export function getMissionPictureId(missionId: string): string | undefined {
  return MAP_PICTURE_IDS[missionId];
}
`
  );
}

const assignments = collectAssignments();
const usedKeys = [...new Set([...assignments.values(), ...(SCREEN_TOPICS as string[])])];
const unused = Object.keys(topics).filter((key) => !usedKeys.includes(key));
if (unused.length) throw new Error(`Topics no unit or screen uses: ${unused.join(', ')}`);
const drawnKeys = usedKeys.filter((key) => typeof topics[key] === 'string');
const entries = buildList(drawnKeys);
writeFileSync(LIST_FILE, JSON.stringify(entries, null, 2) + '\n');
writeIds(assignments);
console.log(`${entries.length} pictures to draw on ${new Set(entries.map((e) => e.sheet)).size} sheets; ${assignments.size} units and missions mapped.`);
